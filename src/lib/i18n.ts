export type Lang = 'en' | 'bn';
export const LANGS: Lang[] = ['en', 'bn'];

/** Homepage path for a language: '/' or '/bn'. */
export const homePath = (lang: Lang) => (lang === 'bn' ? '/bn' : '/');

const BN_DIGITS = '০১২৩৪৫৬৭৮৯';
/** Bengali digits for display numbers (counts, years) on the Bengali page. */
export function num(lang: Lang, n: number | string): string {
  const s = String(n);
  return lang === 'bn' ? s.replace(/[0-9]/g, (d) => BN_DIGITS[Number(d)]) : s;
}

/** Date like "26 Dec 2026" (en) or "২৬ ডিসেম্বর, ২০২৬" (bn), in IST. */
export function formatDate(lang: Lang, value: string, opts: Intl.DateTimeFormatOptions = {}): string {
  const d = /^\d{4}-\d{2}-\d{2}$/.test(value) ? new Date(`${value}T00:00:00+05:30`) : new Date(value);
  return d.toLocaleDateString(lang === 'bn' ? 'bn-IN' : 'en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric',
    timeZone: 'Asia/Kolkata',
    ...opts,
  });
}

